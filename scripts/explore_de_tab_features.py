# ------------------------------------------------------------------------------------------------ split
def split_spec(name: str = "DEV-A", val_seed: int = 20261002) -> dict:
    """Members and cells of a split, from the SH0 registry (nothing hard-coded except the held-out set recipe)."""
    reg = pl.read_parquet(os.path.join(tr.REG, "splits.parquet")).filter(pl.col("split") == name)
    mem, _, folds = tr.registry()
    use = set(tr.usable_members(mem))
    train = sorted(set(reg.filter(pl.col("role") == "train")["src_member"].to_list()) & use)
    assert train, f"no training members for {name}"
    rows = {m: tr.member_row(mem, m) for m in use}
    tgcm = {rows[m]["gcm"] for m in train}
    tseed = {int(rows[m]["seed"]) for m in train}
    tscen = {rows[m]["scen"] for m in train}
    dev = folds.filter(pl.col("is_dev"))
    rng = np.random.default_rng(val_seed)
    val_fold = int(rng.integers(1, 5))
    held = {
        # spatial hold-out: the training members' fold-5 cells
        "F5": train,
        # held-out climate model: other GCM, the training seed, every usable scenario
        "GCM": sorted(m for m in use if rows[m]["gcm"] not in tgcm and int(rows[m]["seed"]) in tseed),
        # held-out scenario (+ binary): training GCM, ssp245 scored against seed 2 (registry test_truth)
        "SCEN": sorted(set(reg.filter(pl.col("role") == "test_truth")["src_member"].to_list()) & use
                       - set(train) - {m for m in use if rows[m]["gcm"] not in tgcm}),
        # held-out seed: the training GCM's other seed in the training scenarios
        "SEED2": sorted(m for m in use if rows[m]["gcm"] in tgcm and int(rows[m]["seed"]) not in tseed
                        and rows[m]["scen"] in tscen),
    }
    held["SCEN"] = [m for m in held["SCEN"] if rows[m]["scen"] != "Historical"]
    return {"split": name, "train": train, "val_fold": val_fold, "val_seed": val_seed,
            "train_folds": [1, 2, 3, 4], "heldout_fold": 5,
            "cells_train": sorted(dev.filter(pl.col("fold") <= 4)["Cell"].to_list()),
            "cells_f5": sorted(dev.filter(pl.col("fold") == 5)["Cell"].to_list()),
            "cells_dev": sorted(dev["Cell"].to_list()),
            "fold_of": dict(zip(dev["Cell"].to_list(), dev["fold"].to_list(), strict=True)),
            "heldout": held, "rows": {m: {k: rows[m][k] for k in ("gcm", "scen", "seed", "bin_feb2026", "npatch")}
                                      for m in use}}


def trans_files(member: str) -> list[str]:
    return sorted(glob.glob(os.path.join(tr.TRANS, CELLSET, member, "cb=*", "y*.parquet")))


def patch_file(member: str, year: int) -> str:
    f = glob.glob(os.path.join(PATCHT, CELLSET, member, "cb=*", f"y{year}.parquet"))
    assert len(f) == 1, (member, year, f)
    return f[0]


# ------------------------------------------------------------------------------------------------ static tables
_STATIC_CACHE: dict = {}


def statics(gcm: str) -> pl.DataFrame:
    """Per cell: soil_code + own-GCM 1985-2014 climatology c85_* (float32)."""
    if gcm not in _STATIC_CACHE:
        c8 = pl.read_parquet(C8514).filter(pl.col("gcm") == gcm).select(
            pl.col("Cell").cast(pl.Int16), *[pl.col(f).cast(pl.Float32).alias(f"c85_{f}") for f in C85_F])
        st = pl.read_parquet(STATIC).select(pl.col("Cell").cast(pl.Int16), pl.col("soil_code").cast(pl.Int16))
        _STATIC_CACHE[gcm] = st.join(c8, on="Cell", how="inner")
    return _STATIC_CACHE[gcm]


# ------------------------------------------------------------------------------------------------ THE assembly
def assemble(df, P=None):
    """Raw columns -> every feature (B0, B1 and the derived inputs). Works on DataFrame and LazyFrame. The SAME
    function is applied to the training frame and to the rollout frame."""
    P = rl.load_params() if P is None else P
    f32 = pl.Float32
    resist = P["resist"]
    own = lambda base: pl.coalesce([pl.when(pl.col("Type") == k).then(pl.col(f"{base.format(k)}").cast(f32))  # noqa: E731
                                     for k in range(MAX_TREE_TYPE + 1)])
    lag = [pl.col(f"frac_loss_lag{k}").cast(f32) for k in range(NLAG)]
    ex = [
        pl.col("agb").cast(f32).log().alias("log_agb"),
        pl.col("vegc").cast(f32).log().alias("log_vegc"),
        (pl.col("d_agb_prev").cast(f32) / pl.col("agb").cast(f32)).alias("rel_dagb_prev"),
        pl.col("is_new_y").fill_null(False).cast(f32).alias("is_new"),
        (pl.col("height_rank").cast(f32) / pl.col("n_live").cast(f32)).alias("rel_rank"),
        *[lag[k].alias(f"flo{k}") for k in range(5)],
        pl.mean_horizontal(lag[5:]).alias("flo_m5_19"),
        *[pl.col(f"anom_{f}_{s}").cast(f32).alias(f"a_{f}_{s}") for f in CLIM_F for s in ("y", "y1")],
        own("anom_tstress_pft{}_y").alias("a_tstress_own_y"),
        own("anom_tstress_pft{}_y1").alias("a_tstress_own_y1"),
        own("tstress_pft{}_y1").alias("tstress_own_y1"),
        *[pl.col(f"anom_{f}_y1").cast(f32).alias(f"a_{f}_y1") for f in TR20],
        pl.col("Type").replace_strict(list(range(len(resist))), [float(x) for x in resist],
                                      return_dtype=f32).alias("resist"),
    ]
    return df.with_columns(ex)


def to_matrix(df: pl.DataFrame, cols: list[str]) -> np.ndarray:
    return df.select([pl.col(c).cast(pl.Float32) for c in cols]).to_numpy().astype(np.float32, copy=False)


# ------------------------------------------------------------------------------------------------ training frame
def raw_training_frame(member: str, year: int, cells: list[int]) -> pl.LazyFrame:
    """SH3 rows of (member, y) on `cells`, with the SH4 cover-loss history of the tree's patch, the climate of y and
    y+1 (tr.join_climate) and the static/climatology columns."""
    files = [f for f in trans_files(member) if f.endswith(f"y{year}.parquet")]
    assert len(files) == 1, (member, year, files)
    lf = pl.scan_parquet(files[0]).filter(pl.col("Cell").is_in(cells))
    ph = pl.scan_parquet(patch_file(member, year)).select(
        "Cell", "Patch", "Year", *RAW_LOSS, "hist_years")
    lf = lf.join(ph, on=["Cell", "Patch", "Year"], how="left")
    lf = tr.join_climate(lf, cols=CLIM_COLS, years=("y", "y1"), ext=True)
    gcm = tr.member_row(tr.registry()[0], member)["gcm"]
    lf = lf.join(statics(gcm).lazy(), on="Cell", how="left")
    return lf


def sample_member(spec: dict, member: str, out_root: str, mode: str, frac: float, cells: list[int]):
    """mode 'train' (stratified + IP weights) or 'eval' (u_hash < frac, unweighted)."""
    od = os.path.join(out_root, member)
    os.makedirs(od, exist_ok=True)
    years = sorted(int(os.path.basename(f)[1:5]) for f in trans_files(member))
    fold = pl.DataFrame({"Cell": list(spec["fold_of"].keys()), "fold": list(spec["fold_of"].values())}).with_columns(
        pl.col("Cell").cast(pl.Int16), pl.col("fold").cast(pl.Int8))
    n_tot = 0
    for y in years:
        fo = os.path.join(od, f"y{y}.parquet")
        if os.path.exists(fo):
            n_tot += pl.scan_parquet(fo).select(pl.len()).collect().item()
            continue
        lf = raw_training_frame(member, y, cells)
        if mode == "train":
            spec1 = ((pl.col("c_y") >= 1) | (pl.col("c_y1").fill_null(0) >= 1) | (pl.col("G_y") < 0)
                     | (pl.col("G_y1").fill_null(1.0) < 0) | (pl.col("fate_y1") >= 1))
            lf = lf.with_columns(stratum=spec1.cast(pl.Int8)).filter(
                (pl.col("stratum") == 1) | (pl.col("u_hash") < frac)).with_columns(
                w_ip=pl.when(pl.col("stratum") == 1).then(1.0).otherwise(1.0 / frac).cast(pl.Float32))
        else:
            lf = lf.filter(pl.col("u_hash") < frac).with_columns(stratum=pl.lit(-1, pl.Int8),
                                                                w_ip=pl.lit(1.0, pl.Float32))
        keep = list(dict.fromkeys(IDS + RAW_TREE + RAW_PATCH + RAW_LOSS + ["hist_years"] + RAW_CLIM + TARGETS
                                  + ["soil_code"] + [f"c85_{f}" for f in C85_F] + ["stratum", "w_ip", "W_y"]))
        df = lf.select(keep).collect().join(fold, on="Cell", how="left")
        df.write_parquet(fo + ".tmp", compression="zstd")
        os.replace(fo + ".tmp", fo)
        n_tot += df.height
        print(f"  {member} y{y}: {df.height} rows", flush=True)
    return n_tot


def stage_samples(a):
    spec = split_spec(a.split)
    base = os.path.join(SAMPLES, a.split)
    json.dump({k: v for k, v in spec.items() if k != "fold_of"}, open(os.path.join(_mk(base), "split.json"), "w"),
              indent=1)
    jobs = []
    for m in spec["train"]:
        jobs.append(("train", m, os.path.join(base, "train"), "train", REST_FRAC, spec["cells_train"]))
    for s, ms in spec["heldout"].items():
        cells = spec["cells_f5"] if s == "F5" else spec["cells_dev"]
        for m in ms:
            jobs.append((s, m, os.path.join(base, "eval", s), "eval", EVAL_FRAC, cells))
    if a.member:
        jobs = [j for j in jobs if j[1] in a.member and (not a.set or j[0] in a.set)]
    if a.set:
        jobs = [j for j in jobs if j[0] in a.set]
    for s, m, od, mode, frac, cells in jobs:
        t0 = time.time()
        n = sample_member(spec, m, od, mode, frac, cells)
        status(f"A1 samples {a.split} {s} {m}: {n} rows ({time.time() - t0:.0f} s)")


def _mk(d):
    os.makedirs(d, exist_ok=True)
    return d



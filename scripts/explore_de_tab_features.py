def stage_report(a):
    spec = split_spec(a.split)
    base = os.path.join(SAMPLES, a.split)
    rep = {"item": "A1", "split": a.split, "val_fold": spec["val_fold"], "train_members": spec["train"],
           "heldout": spec["heldout"], "n_cells": {"train": len(spec["cells_train"]), "f5": len(spec["cells_f5"])},
           "feature_sets": {"B0": B0, "B1": B1, "B1_model_inputs": B1_IN, "next_state": NEXT},
           "rest_frac": REST_FRAC, "eval_frac": EVAL_FRAC, "samples": {}}
    tr_files = glob.glob(os.path.join(base, "train", "*", "*.parquet"))
    if tr_files:
        s = pl.scan_parquet(tr_files).group_by("stratum", "fold").agg(n=pl.len(), w=pl.col("w_ip").sum()).collect()
        rep["samples"]["train"] = s.sort("stratum", "fold").to_dicts()
        rep["samples"]["train_rows"] = int(s["n"].sum())
        rep["samples"]["train_weighted_rows"] = float(s["w"].sum())
    for st in ("F5", "GCM", "SCEN", "SEED2"):
        f = glob.glob(os.path.join(base, "eval", st, "*", "*.parquet"))
        if f:
            rep["samples"][st] = int(pl.scan_parquet(f).select(pl.len()).collect().item())
    for st in ("train", "F5", "GCM", "SCEN", "SEED2"):
        f = glob.glob(os.path.join(base, "recruits", st, "*.parquet"))
        if f:
            rep["samples"][f"recruits_{st}"] = int(pl.scan_parquet(f).select(pl.len()).collect().item())
    au = os.path.join(base, "audit.json")
    if os.path.exists(au):
        A = json.load(open(au))
        rep["audit"] = {k: v for k, v in A.items() if k != "features"}
    rep["feature_sources"] = feature_sources()
    json.dump(rep, open(REPORT, "w"), indent=1)
    print(json.dumps({k: v for k, v in rep.items() if k not in ("feature_sources",)}, indent=1)[:4000])


def feature_sources() -> dict:
    """Where each feature comes from in training vs in the rollout (the feature audit's map)."""
    src = {}
    for f in B0:
        if f in TRAITS or f == "Type":
            src[f] = ("SH3 row", "state.tree (immutable)")
        elif f in ("Height", "LAI", "fpc_ind", "D95", "Age", "log_agb", "log_vegc"):
            src[f] = ("SH3 row", "state.tree (updated by the growth/closure heads + allometry; Age += 1)")
        elif f in ("c_y", "G_y"):
            src[f] = ("SH3 recovered hidden state", "state.tree c, G (G sampled by the growth-efficiency head, c by "
                      "the counter rule)")
        elif f in ("d_agb_prev", "rel_dagb_prev", "is_new"):
            src[f] = ("SH3 history columns", "stepper: d_agb_prev = agb_y1 - agb_y; NaN + aux_tree is_new for "
                      "recruits and spin-in trees")
        elif f.startswith("flo"):
            src[f] = ("SH4 frac_loss_lag*", "state.patch loss_ring (engine-owned)")
        elif f.startswith("grass"):
            src[f] = ("SH3 grass columns", "state.patch grass* (grass head or persistence)")
        elif f.startswith("c85_") or f == "soil_code":
            src[f] = ("SH1 clim8514 / cell_static", "same tables (static per cell)")
        else:
            src[f] = ("SH3 patch/cell context", "recomputed from printed living trees of the state (roster_raw)")
    for f in B1:
        src[f] = ("tr.join_climate (y, y+1)", "Climate provider frames: y+1 = step()'s clim_y1, y = the previous "
                  "step's clim_y1 cached by the stepper (first step: provider read in init)")
    return src



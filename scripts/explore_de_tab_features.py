def add_eligibility(df: pl.DataFrame, P=None) -> pl.DataFrame:
    """rl.eligible on the y+1 climate (20-yr tcold/twarm, current gdd5, prec_ann) — the C-faithful basis."""
    P = rl.load_params() if P is None else P
    E = rl.eligible(df["tcold_month_tr20_y1"].to_numpy(), df["twarm_month_tr20_y1"].to_numpy(),
                    df["gdd5_y1"].to_numpy(), df["prec_ann_y1"].to_numpy(), P)
    return df.with_columns(*[pl.Series(f"elig_t{k}_y1", E[:, k].astype(np.float32)) for k in RECR_TYPES],
                           pl.Series("n_elig_y1", E[:, :MAX_TREE_TYPE + 1].sum(axis=1).astype(np.float32)))


def stage_recruits(a):
    spec = split_spec(a.split)
    base = _mk(os.path.join(SAMPLES, a.split, "recruits"))
    jobs = [("train", m, spec["cells_train"]) for m in spec["train"]]
    jobs += [("F5", m, spec["cells_f5"]) for m in spec["train"]]
    for s in ("GCM", "SCEN", "SEED2"):
        jobs += [(s, m, spec["cells_dev"]) for m in spec["heldout"][s]]
    P = rl.load_params()
    fold = pl.DataFrame({"Cell": list(spec["fold_of"].keys()), "fold": list(spec["fold_of"].values())}).with_columns(
        pl.col("Cell").cast(pl.Int16), pl.col("fold").cast(pl.Int8))
    for s, m, cells in jobs:
        fo = os.path.join(_mk(os.path.join(base, s)), f"{m}.parquet")
        if os.path.exists(fo):
            continue
        t0 = time.time()
        gcm = spec["rows"][m]["gcm"]
        parts = []
        for f in sorted(glob.glob(os.path.join(RECRT, CELLSET, m, "cb=*", "y*.parquet"))):
            y = int(os.path.basename(f)[1:5])
            R = pl.read_parquet(f).filter(pl.col("Cell").is_in(cells) & (pl.col("Type") <= MAX_TREE_TYPE))
            if R.height == 0:
                continue
            Pc, Cc = patch_type_comp(m, y, cells, RECR_TYPES)
            ph = pl.read_parquet(patch_file(m, y)).select("Cell", "Patch", "Year", "frac_loss_lag0")
            R = (R.drop("frac_loss_lag0").join(Pc, on=["Cell", "Patch"], how="left")
                 .join(Cc, on="Cell", how="left").join(ph, on=["Cell", "Patch", "Year"], how="left"))
            for k in RECR_TYPES:
                R = R.with_columns(pl.col(f"pt_n_t{k}").fill_null(0), pl.col(f"pt_agb_t{k}").fill_null(0.0))
            R = tr.join_climate(R, cols=RECR_CLIM, years=("y1",), ext=True)
            R = add_eligibility(R, P).join(statics(gcm), on="Cell", how="left")
            parts.append(R)
        D = pl.concat(parts, how="diagonal_relaxed").join(fold, on="Cell", how="left")
        D = D.with_columns(member=pl.lit(m), u_rec=pl.Series(tr.u_hash(D, m)))
        D.write_parquet(fo, compression="zstd")
        status(f"A1 recruits {s} {m}: {D.height} rows ({time.time() - t0:.0f} s)")


# ------------------------------------------------------------------------------------------------ rollout frame
def roster_raw(state, clim_y: pl.DataFrame, clim_y1: pl.DataFrame, gcm: str) -> pl.DataFrame:
    """The raw-column frame of the ROLLOUT, built only from the engine's RosterState and the climate provider's
    frames of y and y+1 (cell order = state.cell['cells']). Rows = every tree of the state (hidden ones included,
    so the output aligns with state.tree); patch/cell context counts PRINTED living trees only, like the table."""
    t = state.tree
    n = state.n
    vis = ~np.asarray(t["hidden"], bool) & ~np.asarray(t["isdead"], bool)
    pidx = state.patch_index()
    npt = len(state.cell["cells"]) * state.npatch
    fpc = np.where(vis, t["fpc_ind"].astype(np.float64), 0.0)
    agb = np.where(vis, t["agb"].astype(np.float64), 0.0)
    n_live = np.bincount(pidx, weights=vis.astype(np.float64), minlength=npt)
    s_fpc = np.bincount(pidx, weights=fpc, minlength=npt)
    s_agb = np.bincount(pidx, weights=agb, minlength=npt)
    H = t["Height"].astype(np.float64)
    # height rank ('min' method, descending) and fpc of strictly taller printed stems, within the patch
    order = np.lexsort((-H, pidx))
    ps, hs, fs, vs = pidx[order], H[order], fpc[order], vis[order]
    rank = np.zeros(n, np.int64)
    above = np.zeros(n, np.float64)
    if n:
        newp = np.r_[True, ps[1:] != ps[:-1]]
        newh = newp | np.r_[True, hs[1:] != hs[:-1]]
        cvis = np.cumsum(vs)
        cfpc = np.cumsum(fs)
        pstart = np.maximum.accumulate(np.where(newp, np.arange(n), 0))
        hstart = np.maximum.accumulate(np.where(newh, np.arange(n), 0))
        base_v = np.where(pstart > 0, cvis[pstart - 1], 0)
        base_f = np.where(pstart > 0, cfpc[pstart - 1], 0.0)
        before_v = np.where(hstart > 0, cvis[hstart - 1], 0) - base_v
        before_f = np.where(hstart > 0, cfpc[hstart - 1], 0.0) - base_f
        rank[order] = before_v + 1
        above[order] = before_f
    ci = state.cell_index(t["Cell"])
    ncell = len(state.cell["cells"])
    cell_n = np.bincount(ci, weights=vis.astype(np.float64), minlength=ncell)
    ring = state.patch["loss_ring"]
    raw = {k: t[k] for k in ["Type"] + TRAITS + ["Height", "agb", "vegc", "LAI", "fpc_ind", "D95", "Age"]}
    raw.update({"Cell": t["Cell"], "Patch": t["Patch"], "c_y": t["c"], "G_y": t["G"],
                "d_agb_prev": t["d_agb_prev"], "is_new_y": np.asarray(state.aux_tree.get(
                    "is_new", np.zeros(n, bool)), bool),
                "n_live": n_live[pidx].astype(np.int16), "sum_fpc": s_fpc[pidx].astype(np.float32),
                "sum_agb": s_agb[pidx].astype(np.float32), "height_rank": rank.astype(np.int16),
                "fpc_above": above.astype(np.float32),
                "cell_stems_per_patch": (cell_n[ci] / state.npatch).astype(np.float32)})
    for g in grass_cols():
        raw[g] = state.patch[g][pidx] if g in state.patch else np.full(n, np.nan, np.float32)
    for k in range(NLAG):
        raw[f"frac_loss_lag{k}"] = ring[pidx, k]
    df = pl.DataFrame(raw)
    for suf, cf in (("y", clim_y), ("y1", clim_y1)):
        c = cf.select(pl.col("Cell").cast(pl.Int16), *[pl.col(x).alias(f"{x}_{suf}") for x in CLIM_COLS])
        df = df.join(c, on="Cell", how="left", maintain_order="left")
    df = df.join(statics(gcm), on="Cell", how="left", maintain_order="left")
    assert df.height == n
    return df


def init_conventions(state, spinin: np.ndarray, start_year: int, chain_first_year: int = 1985):
    """Rollout convention for an SH5 start roster, matching the training table: a tree not printed in the year
    before the start (SH5 `spinin`) has an unknown last-year change (d_agb_prev = NaN, as the table's null) and is
    'new' (is_new_y = True) — except at the chain's first year, where the table has no previous year at all and
    carries is_new_y = null (-> False) for every tree."""
    spinin = np.asarray(spinin, bool)
    state.tree["d_agb_prev"] = np.where(spinin, np.nan, state.tree["d_agb_prev"]).astype(np.float32)
    state.aux_tree["is_new"] = spinin & (start_year > chain_first_year)


# ------------------------------------------------------------------------------------------------ audit
def stage_audit(a):
    """Rebuild the rollout frame from an SH5 initial state (MPI Historical s1 2014 by default) and the engine's
    climate provider, and compare every B0/B1/derived feature with the training frame (SH3 + join_climate) of the
    same trees and year (the ssp member's y = 2014 rows). Hidden state that the init fills differently (spin-in
    d_agb_prev) is reported, not hidden."""
    import explore_de_engine as en
    spec = split_spec(a.split)
    m = a.audit_member or [x for x in spec["train"] if "ssp" in x][0]
    row = spec["rows"][m]
    gcm, seed, scen = row["gcm"], int(row["seed"]), row["scen"]
    Y = 2014
    cells = np.array(spec["cells_dev"][:: max(1, a.audit_stride)], dtype=np.int32)
    state = en.load_init(f"{gcm}_Historical_s{seed}_{Y}", CELLSET, cells)
    init_trees = pl.read_parquet(glob.glob(os.path.join(XDE, "shared", "init", CELLSET,
                                                        f"{gcm}_Historical_s{seed}_{Y}", "cb=*", "trees.parquet"))[0])
    spin = init_trees.filter(pl.col("Cell").is_in(cells.tolist())).sort(["Cell", "Patch", "Type", "ID"])["spinin"]
    # the rollout convention for spin-in trees: unknown last-year change = NaN (as in the chain's first table year)
    init_conventions(state, spin.to_numpy(), Y)
    ch = en.Climate(gcm, "Historical", seed, state.cell["cells"], "actual")
    c1 = en.Climate(gcm, scen, seed, state.cell["cells"], "actual")
    R = roster_raw(state, ch.year(Y), c1.year(Y + 1), gcm)
    R = tr.with_key(R.with_columns(ID=pl.Series(state.tree["ID"])))
    Tt = raw_training_frame(m, Y, cells.tolist()).collect()
    FR = assemble(R)
    FT = assemble(Tt)
    J = FT.join(FR, on=tr.KEY, how="full", suffix="_r", coalesce=True)
    out = {"member": m, "year": Y, "cells": int(len(cells)), "rows_train": FT.height, "rows_roll": FR.height,
           "rows_joined": J.height, "unmatched_train": int(J["log_agb_r"].is_null().sum()),
           "unmatched_roll": int(J["log_agb"].is_null().sum()), "spinin_rows": int(spin.sum()), "features": {}}
    feats = [f for f in dict.fromkeys(B0 + B1 + ["resist"]) if f not in tr.KEY]
    for f in feats:
        x = J[f].cast(pl.Float64).to_numpy()
        y = J[f + "_r"].cast(pl.Float64).to_numpy()
        both_nan = np.isnan(x) & np.isnan(y)
        eq = both_nan | (np.abs(x - y) <= 1e-5 * np.maximum(1.0, np.abs(x)))
        out["features"][f] = {"n": int(len(x)), "mismatch": int((~eq).sum()),
                              "max_abs_diff": float(np.nanmax(np.abs(x - y))) if (~both_nan).any() else 0.0}
    bad = {f: v for f, v in out["features"].items() if v["mismatch"]}
    out["features_with_mismatch"] = bad
    out["pass"] = (not bad or set(bad) <= {"d_agb_prev", "rel_dagb_prev"}) and out["unmatched_train"] == 0 \
        and out["unmatched_roll"] == 0
    if bad.get("d_agb_prev"):
        out["note_d_agb_prev"] = ("mismatch rows must equal the spin-in rows whose training value is known: the "
                                  "init fills them with a per-Type median; the rollout convention sets NaN")
        dm = J.filter(pl.col("d_agb_prev").is_not_null() & pl.col("d_agb_prev_r").is_null()).height
        out["d_agb_prev_mismatch_explained_by_spinin"] = int(dm)
    json.dump(out, open(os.path.join(_mk(os.path.join(SAMPLES, a.split)), "audit.json"), "w"), indent=1)
    status(f"A1 audit {m} {Y}: pass={out['pass']}, mismatching features {sorted(bad)}")
    print(json.dumps({k: v for k, v in out.items() if k != "features"}, indent=1), flush=True)



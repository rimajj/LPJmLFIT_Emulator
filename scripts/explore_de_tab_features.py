def stage_submit(a):
    logs = os.path.join(REPO, "logs")
    os.makedirs(logs, exist_ok=True)
    jobs = os.path.join(_mk(os.path.join(TAB, "_jobs")), f"A1_{a.what}.sh")
    me = os.path.abspath(__file__)
    if a.what == "samples":
        spec = split_spec(a.split)
        mems = list(dict.fromkeys(spec["train"] + sum(spec["heldout"].values(), [])))
        lines = [f"{PY} {me} samples --split {a.split} --member {m}" for m in mems]
        with open(jobs + ".tasks", "w") as fh:
            fh.write("\n".join(lines) + "\n")
        body = (f"#!/bin/bash\n#SBATCH --account=waldspektrum --partition=priority --qos=priority\n"
                f"#SBATCH --cpus-per-task=4 --time=02:00:00 --array=1-{len(lines)}%6\n"
                f"#SBATCH --job-name=X-de-A1-samples --output={logs}/X-de-A1-samples.%A_%a.out\n"
                f"export POLARS_MAX_THREADS=4\n"
                f"eval \"$(sed -n ${{SLURM_ARRAY_TASK_ID}}p {jobs}.tasks)\"\n")
    else:
        body = (f"#!/bin/bash\n#SBATCH --account=waldspektrum --partition=priority --qos=priority\n"
                f"#SBATCH --cpus-per-task=8 --time=02:00:00\n"
                f"#SBATCH --job-name=X-de-A1-{a.what} --output={logs}/X-de-A1-{a.what}.%j.out\n"
                f"export POLARS_MAX_THREADS=8\n{PY} {me} {a.what} --split {a.split}\n")
    with open(jobs, "w") as fh:
        fh.write(body)
    out = os.popen(f"sbatch {jobs}").read().strip()
    status(f"A1 submit {a.what}: {out} ({jobs})")



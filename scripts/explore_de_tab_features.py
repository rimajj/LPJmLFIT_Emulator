#!/usr/bin/env python3
"""explore_de_tab_features.py — LINE X, Germany data-driven emulator, design track A-TAB, item A1:
FEATURE MODULE + STRATIFIED TRAINING SAMPLES for the per-tree gradient-boosted transition heads.

ONE feature code path for training and rollout. Every feature is computed by `assemble()` from a frame of RAW
columns; the raw frame comes from
  training  `raw_training_frame()`  = SH3 transition table (explore_de_sh_trans) + SH4 patch cover-loss history
            + tr.join_climate() (the only allowed climate join) + SH1 own-GCM 1985-2014 climatology + soil code
  rollout   `roster_raw(state, clim_y, clim_y1)` = the engine's RosterState (explore_de_engine) + the climate
            provider's frames of year y and y+1 + the same climatology/soil tables.
`audit` rebuilds the rollout frame from an SH5 initial state and checks every feature against the training frame
of the same trees and year (the proof that every input is regenerated by carried rollout state).

FEATURE SETS (names as produced by assemble())
  B0 state    Type, the 6 traits, Height, log_agb, log_vegc, LAI, fpc_ind, D95, Age, c_y, G_y, d_agb_prev,
              rel_dagb_prev, is_new; patch n_live, sum_fpc, sum_agb, height_rank, rel_rank, fpc_above, grass<t>_*,
              cell_stems_per_patch, the cover-loss ring flo0..flo4 + flo_m5_19 (fraction of the patch's printed
              living crown cover lost in each of the last years); soil_code; c85_* (own-GCM 1985-2014 climatology)
  B1 climate  a_<f>_y and a_<f>_y1 (anomaly vs the cell's own-GCM 1985-2014 mean) for 17 annual features, the
              tree's OWN-PFT temperature-stress-day anomaly (y, y+1) and absolute count (y+1), the 20-yr trailing
              anomalies of tcold/twarm/gdd5 (y+1), and ABSOLUTE tmean_ann / twarm_month of y+1
  B1 model inputs = B1 + (Type, log_agb): the climate booster may modulate by PFT and size, nothing else.
  CO2, wind, lon/lat and the cell id are never features.

SPLIT  `split_spec(name)` — DEV-A: train = the registry's role == "train" members (MPI-ESM1-2-HR seed 1:
  Historical 1985-2013 + ssp126 + ssp370 2014-2043) on the dev cells of block folds 1-4; one of folds 1-4 (seeded
  random) is the early-stopping validation fold; held out: fold-5 cells (F5), ACCESS-CM2 seed 1 (GCM), MPI ssp245
  seed 2 (SCEN), MPI seed 2 Historical/ssp126/ssp370 (SEED2). Never trained on.

SAMPLES  /p/tmp/jamirp/X_de/tab/samples/<split>/
  train/<member>/y<Y>.parquet   folds 1-4 rows: ALL rows with c_y >= 1 or c_y1 >= 1 or G_y < 0 or G_y1 < 0 or
                                fate_y1 >= 1 (stratum 1, weight 1) + rows with u_hash < 0.10 of the rest
                                (stratum 0, weight 10 = inverse inclusion probability); column `fold`
  eval/<set>/<member>/y<Y>.parquet  u_hash < EVAL_FRAC unweighted rows of every held-out set
  recruits/<role>/<member>.parquet  recruit rows (Type target) + patch/cell composition by Type (heads H8/H9)
STAGES  samples [--member M] | recruits | audit | submit | report
"""

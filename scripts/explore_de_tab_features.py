def patch_type_comp(member: str, year: int, cells: list[int], types: list[int]) -> tuple[pl.DataFrame, pl.DataFrame]:
    """Per (Cell, Patch) and per Cell at y: living printed stem counts and agb by tree Type (from SH3 rows)."""
    files = [f for f in trans_files(member) if f.endswith(f"y{year}.parquet")]
    t = pl.scan_parquet(files[0]).filter(pl.col("Cell").is_in(cells)).select(
        "Cell", "Patch", "Type", pl.col("agb").cast(pl.Float64)).collect()
    return comp_from_trees(t, types)


def comp_from_trees(t: pl.DataFrame, types: list[int]) -> tuple[pl.DataFrame, pl.DataFrame]:
    """Shared by training and rollout: per-patch and per-cell composition by Type from (Cell, Patch, Type, agb)."""
    pt = t.group_by("Cell", "Patch", "Type").agg(n=pl.len(), a=pl.col("agb").cast(pl.Float64).sum())
    ce = t.group_by("Cell", "Type").agg(n=pl.len(), a=pl.col("agb").cast(pl.Float64).sum())
    P = t.select("Cell", "Patch").unique()
    C = t.select("Cell").unique()
    for k in types:
        P = P.join(pt.filter(pl.col("Type") == k).select("Cell", "Patch", pl.col("n").alias(f"pt_n_t{k}"),
                                                          pl.col("a").alias(f"pt_agb_t{k}")),
                   on=["Cell", "Patch"], how="left")
        C = C.join(ce.filter(pl.col("Type") == k).select("Cell", pl.col("n").alias(f"ce_n_t{k}"),
                                                          pl.col("a").alias(f"ce_agb_t{k}")), on="Cell", how="left")
    P = P.fill_null(0)
    C = C.fill_null(0)
    nt = sum(pl.col(f"ce_n_t{k}") for k in types)
    at = sum(pl.col(f"ce_agb_t{k}") for k in types)
    C = C.with_columns(*[(pl.col(f"ce_n_t{k}") / nt).cast(pl.Float32).alias(f"ce_share_t{k}") for k in types],
                       *[(pl.col(f"ce_agb_t{k}") / at).cast(pl.Float32).alias(f"ce_agbshare_t{k}") for k in types])
    return P, C


